def build_orders(customers):
    orders, items, payments = [], [], []
    buyers = [c for c in customers if c[0] not in CUSTOMERS_WITHOUT_ORDERS]
    sellable = [i for i in range(1, len(PRODUCT_SEEDS) + 1) if i not in PRODUCTS_NEVER_SOLD]
    order_id = 1000
    payment_id = 1
    start = dt.date(2023, 1, 1)
    span = (TODAY - start).days
    for _ in range(620):
        order_id += 1
        cid = RNG.choice(buyers)[0]
        order_date = start + dt.timedelta(days=RNG.randint(0, span))
        status = RNG.choice(STATUSES)
        rep = RNG.choice(SALES_REPS) if RNG.random() > 0.08 else None
        if status in ("completed", "returned"):
            ship = order_date + dt.timedelta(days=RNG.randint(1, 9))
        elif status == "shipped":
            ship = order_date + dt.timedelta(days=RNG.randint(1, 4))
        else:
            ship = None
        ship_country = None
        for c in customers:
            if c[0] == cid:
                ship_country = c[4]
                break
        shipping = round(RNG.uniform(0, 45), 2)
        orders.append([order_id, cid, rep, d(order_date),
                       d(ship) if ship else None, status, shipping, ship_country])

        n_items = RNG.choices([1, 2, 3, 4, 5], weights=[35, 28, 20, 11, 6])[0]
        chosen = RNG.sample(sellable, n_items)
        total = shipping
        for item_no, pid in enumerate(chosen, start=1):
            base = PRODUCT_SEEDS[pid - 1][2]
            qty = RNG.choices([1, 1, 1, 2, 2, 3, 4, 6], weights=[30, 20, 15, 15, 8, 6, 4, 2])[0]
            discount = RNG.choice([0, 0, 0, 0, 0.05, 0.10, 0.15, 0.20])
            price = round(base * RNG.uniform(0.97, 1.03), 2)
            total += price * qty * (1 - discount)
            items.append([order_id, item_no, pid, qty, price, discount])

        if status in ("completed", "shipped", "returned"):
            paid = (ship or order_date)
            payments.append([payment_id, order_id, RNG.choice(METHODS),
                             round(total, 2), ts(paid, RNG.randint(8, 21), RNG.randint(0, 59))])
            payment_id += 1
            # a handful of orders are settled in two instalments
            if RNG.random() < 0.05:
                payments.append([payment_id, order_id, "gift_card",
                                 round(total * 0.25, 2),
                                 ts(paid + dt.timedelta(days=1), RNG.randint(8, 21), RNG.randint(0, 59))])
                payment_id += 1
    return orders, items, payments


