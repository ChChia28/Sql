def build_sessions(customers):
    """One row per visit. Days are deliberately missing here and there so the
    advanced 'gaps and islands' lessons have something to find."""
    sessions = []
    sid = 1
    day = dt.date(2025, 1, 1)
    while day <= TODAY:
        # skip roughly one day in seven -> gaps in the daily series
        if RNG.random() < 0.14:
            day += dt.timedelta(days=1)
            continue
        for _ in range(RNG.randint(1, 6)):
            cid = RNG.choice(customers)[0] if RNG.random() > 0.35 else None
            sessions.append([sid, cid, ts(day, RNG.randint(0, 23), RNG.randint(0, 59)),
                             RNG.randint(20, 3600), RNG.choice(DEVICES),
                             RNG.choice(LANDING_PAGES)])
            sid += 1
        day += dt.timedelta(days=1)
    return sessions


