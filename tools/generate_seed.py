def q(value) -> str:
    """Render a Python value as a SQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int,)):
        return str(value)
    if isinstance(value, float):
        return f"{value:.2f}"
    return "'" + str(value).replace("'", "''") + "'"


def row(values) -> str:
    return "(" + ", ".join(q(v) for v in values) + ")"


def insert(table: str, columns: list[str], rows: list[list]) -> str:
    """Multi-row INSERT, chunked so no single statement gets unwieldy."""
    out = []
    for i in range(0, len(rows), 50):
        chunk = rows[i:i + 50]
        head = f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n"
        out.append(head + ",\n".join("  " + row(r) for r in chunk) + ";\n")
    return "\n".join(out)


def d(date: dt.date) -> str:
    return date.isoformat()


def ts(date: dt.date, hour: int, minute: int, second: int = 0) -> str:
    return f"{date.isoformat()} {hour:02d}:{minute:02d}:{second:02d}"


